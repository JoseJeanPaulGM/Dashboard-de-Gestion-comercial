CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_app_users_username CHECK (username ~ '^[a-z][a-z0-9._-]{2,63}$'),
    CONSTRAINT ck_app_users_token_version CHECK (token_version >= 0)
);

CREATE TABLE roles (
    code VARCHAR(32) PRIMARY KEY
);

CREATE TABLE permissions (
    code VARCHAR(48) PRIMARY KEY
);

CREATE TABLE role_permissions (
    role_code VARCHAR(32) NOT NULL REFERENCES roles(code),
    permission_code VARCHAR(48) NOT NULL REFERENCES permissions(code),
    PRIMARY KEY (role_code, permission_code)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    role_code VARCHAR(32) NOT NULL REFERENCES roles(code),
    PRIMARY KEY (user_id, role_code)
);

CREATE TABLE refresh_sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_refresh_sessions_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_refresh_sessions_user_active ON refresh_sessions(user_id) WHERE revoked_at IS NULL;

