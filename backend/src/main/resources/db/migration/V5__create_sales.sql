CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total NUMERIC(20, 2) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_sales_status CHECK (status IN ('DRAFT', 'CONFIRMED')),
    CONSTRAINT ck_sales_total CHECK (total > 0),
    CONSTRAINT ck_sales_confirmation CHECK (
        (status = 'DRAFT' AND confirmed_at IS NULL) OR
        (status = 'CONFIRMED' AND confirmed_at IS NOT NULL)
    )
);

CREATE INDEX ix_sales_customer ON sales (customer_id);
CREATE INDEX ix_sales_status_created ON sales (status, created_at);

CREATE TABLE sale_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(20, 2) NOT NULL,
    CONSTRAINT fk_sale_lines_sale FOREIGN KEY (sale_id) REFERENCES sales (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_lines_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT uk_sale_lines_sale_product UNIQUE (sale_id, product_id),
    CONSTRAINT ck_sale_lines_quantity CHECK (quantity BETWEEN 1 AND 1000000),
    CONSTRAINT ck_sale_lines_price CHECK (unit_price > 0),
    CONSTRAINT ck_sale_lines_subtotal CHECK (subtotal = quantity * unit_price)
);

CREATE INDEX ix_sale_lines_product ON sale_lines (product_id);
