CREATE TABLE purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total NUMERIC(20, 2) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_purchases_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE RESTRICT,
    CONSTRAINT ck_purchases_status CHECK (status IN ('DRAFT', 'CONFIRMED')),
    CONSTRAINT ck_purchases_total CHECK (total > 0),
    CONSTRAINT ck_purchases_confirmation CHECK (
        (status = 'DRAFT' AND confirmed_at IS NULL) OR
        (status = 'CONFIRMED' AND confirmed_at IS NOT NULL)
    )
);

CREATE INDEX ix_purchases_supplier ON purchases (supplier_id);
CREATE INDEX ix_purchases_status_created ON purchases (status, created_at);

CREATE TABLE purchase_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    subtotal NUMERIC(20, 2) NOT NULL,
    CONSTRAINT fk_purchase_lines_purchase FOREIGN KEY (purchase_id) REFERENCES purchases (id) ON DELETE RESTRICT,
    CONSTRAINT fk_purchase_lines_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT uk_purchase_lines_purchase_product UNIQUE (purchase_id, product_id),
    CONSTRAINT ck_purchase_lines_quantity CHECK (quantity BETWEEN 1 AND 1000000),
    CONSTRAINT ck_purchase_lines_price CHECK (unit_price > 0),
    CONSTRAINT ck_purchase_lines_subtotal CHECK (subtotal = quantity * unit_price)
);

CREATE INDEX ix_purchase_lines_product ON purchase_lines (product_id);

CREATE TABLE inventory_balances (
    product_id BIGINT PRIMARY KEY,
    quantity BIGINT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_inventory_balances_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT ck_inventory_balances_quantity CHECK (quantity >= 0)
);
