ALTER TABLE inventory_balances
    ADD COLUMN minimum_quantity BIGINT NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_inventory_balances_minimum CHECK (minimum_quantity >= 0);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    quantity_change BIGINT NOT NULL,
    balance_after BIGINT NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    source_id BIGINT,
    request_key UUID,
    reason VARCHAR(500),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_inventory_movements_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT ck_inventory_movements_balance CHECK (balance_after >= 0),
    CONSTRAINT ck_inventory_movements_source CHECK (
        (source_type = 'OPENING' AND source_id IS NOT NULL AND source_id = product_id
            AND request_key IS NULL
            AND reason IS NULL AND quantity_change > 0)
        OR (source_type = 'PURCHASE' AND source_id IS NOT NULL AND source_id > 0
            AND request_key IS NULL
            AND reason IS NULL AND quantity_change > 0)
        OR (source_type = 'SALE' AND source_id IS NOT NULL AND source_id > 0
            AND request_key IS NULL
            AND reason IS NULL AND quantity_change < 0)
        OR (source_type = 'ADJUSTMENT' AND source_id IS NULL AND request_key IS NOT NULL
            AND reason IS NOT NULL AND quantity_change <> 0)
    )
);

CREATE UNIQUE INDEX uk_inventory_movements_source
    ON inventory_movements (source_type, source_id)
    WHERE source_id IS NOT NULL;
CREATE UNIQUE INDEX uk_inventory_movements_request_key
    ON inventory_movements (request_key)
    WHERE request_key IS NOT NULL;
CREATE INDEX ix_inventory_movements_product_id
    ON inventory_movements (product_id, id DESC);
CREATE INDEX ix_inventory_balances_low_stock
    ON inventory_balances (quantity, minimum_quantity)
    WHERE minimum_quantity > 0;

